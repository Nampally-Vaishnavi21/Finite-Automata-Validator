"""Regenerate the diagrams, transition tables and test results in docs/ from the
actual automata, so the documentation can never disagree with the code.

    python scripts/build_docs.py

PNG images are produced only if the Graphviz `dot` program is installed;
the .dot sources are always written.
"""
import csv
import os
import shutil
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from automata import APPLICATIONS, email_dfa, password_dfa, pin_dfa  # noqa: E402

DOCS = os.path.join(ROOT, "docs")
DIAGRAMS = os.path.join(DOCS, "diagrams")


def md_table(rows) -> str:
    heads = list(rows[0].keys())
    out = ["| " + " | ".join(heads) + " |", "|" + "|".join(["---"] * len(heads)) + "|"]
    for r in rows:
        out.append("| " + " | ".join(str(r[h]).replace("|", "\\|") for h in heads) + " |")
    return "\n".join(out)


def write_diagram(name: str, dot: str) -> None:
    path = os.path.join(DIAGRAMS, name + ".dot")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(dot.replace('bgcolor="transparent"', 'bgcolor="white"'))
    if shutil.which("dot"):
        subprocess.run(["dot", "-Tpng", "-Gdpi=150", path, "-o",
                        os.path.join(DIAGRAMS, name + ".png")], check=True)


def main() -> None:
    os.makedirs(DIAGRAMS, exist_ok=True)
    write_diagram("password_components", password_dfa.components_dot())
    write_diagram("email_dfa", email_dfa.DFA_EMAIL.to_dot())
    write_diagram("pin_dfa", pin_dfa.DFA_PIN.to_dot())

    # ---- transition tables
    parts = ["# Transition Tables", "",
             "Generated by `scripts/build_docs.py`. `→` marks the start state, `*` a final state.", ""]
    parts += ["## 1. Password DFA (product of five components)", ""]
    for comp in password_dfa.COMPONENTS:
        parts += [f"### Component: {comp.name}", "", md_table(comp.transition_table()), ""]
    pw = password_dfa.DFA_PASSWORD
    parts += [f"Product automaton: {len(pw.states)} states, {len(pw.reachable_states())} reachable, "
              f"{pw.minimal_state_count()} after minimisation. The complete product table is in "
              "`password_product_transition_table.csv`.", ""]
    parts += ["## 2. Email DFA", "", md_table(email_dfa.DFA_EMAIL.transition_table()), "",
              f"Minimal DFA: {email_dfa.DFA_EMAIL.minimal_state_count()} states.", ""]
    parts += ["## 3. ATM PIN DFA", "", md_table(pin_dfa.DFA_PIN.transition_table()), "",
              f"Minimal DFA: {pin_dfa.DFA_PIN.minimal_state_count()} states.", ""]
    with open(os.path.join(DOCS, "TRANSITION_TABLES.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(parts))

    with open(os.path.join(DOCS, "password_product_transition_table.csv"), "w",
              newline="", encoding="utf-8") as fh:
        writer = csv.writer(fh)
        writer.writerow(["state (n,ULDS)", "start", "final", "reachable"]
                        + [pw.class_labels[c] for c in pw.classes])
        reach = set(pw.reachable_states())
        for q in pw.states:
            writer.writerow([pw.state_label(q), q == pw.start, q in pw.finals, q in reach]
                            + [pw.state_label(pw.delta[(q, c)]) for c in pw.classes])

    # ---- test results (actual runs)
    parts = ["# Test Results", "",
             "Generated by running every listed test string through its DFA "
             "(`python scripts/build_docs.py`).", ""]
    for key, (dfa, spec, cases) in APPLICATIONS.items():
        rows, passed = [], 0
        for i, (text, expected, why) in enumerate(cases, start=1):
            res = dfa.run(text)
            passed += res.accepted == expected
            rows.append({"#": i, "Test string": f"`{text}`" if text else "ε (empty)",
                         "Purpose": why, "Expected": "accept" if expected else "reject",
                         "DFA result": "ACCEPTED" if res.accepted else "REJECTED",
                         "Final state": dfa.state_label(res.final_state),
                         "Test": "PASS" if res.accepted == expected else "FAIL"})
        parts += [f"## {spec['title']}", "", md_table(rows), "",
                  f"Passed: {passed} / {len(cases)}", ""]
    with open(os.path.join(DOCS, "TEST_RESULTS.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(parts))
    print("docs regenerated")


if __name__ == "__main__":
    main()
