"""Regenerate the diagrams and the transition-table document from the code.

    python scripts/build_assets.py

Writes diagrams/*.dot always, and diagrams/*.png when the Graphviz `dot`
program is installed.  Writes docs/transition_tables.md.
Because everything is generated from the same DFA objects the app uses, the
documents can never disagree with the program.
"""
import os
import shutil
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from automata import build_email_dfa, build_password_dfa, build_pin_dfa   # noqa: E402
from automata import password_dfa                                         # noqa: E402

PWD, EMAIL, PIN = build_password_dfa(), build_email_dfa(), build_pin_dfa()

diagrams = {
    "pin_dfa": PIN.to_dot(),
    "pin_dfa_with_trap": PIN.to_dot(show_trap=True),
    "email_dfa": EMAIL.to_dot(),
    "password_length_dfa": password_dfa.length_dot(),
    "password_product_dfa": PWD.to_dot(rankdir="TB"),
}
for kind in password_dfa.FLAG_ORDER:
    diagrams[f"password_contains_{kind}_dfa"] = password_dfa.contains_dot(kind)

out = os.path.join(ROOT, "diagrams")
os.makedirs(out, exist_ok=True)
have_dot = shutil.which("dot") is not None
for name, dot in diagrams.items():
    path = os.path.join(out, name + ".dot")
    with open(path, "w", encoding="utf-8") as f:
        f.write(dot.replace('bgcolor="transparent"', 'bgcolor="white"'))
    if have_dot:
        subprocess.run(["dot", "-Tpng", "-Gdpi=150", path, "-o", path[:-4] + ".png"], check=True)
print(f"{len(diagrams)} diagrams written to diagrams/ (PNG: {'yes' if have_dot else 'no - install Graphviz'})")


def md_table(rows):
    head = list(rows[0])
    lines = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    lines += ["| " + " | ".join(str(r[h]).replace("|", "\\|") for h in head) + " |" for r in rows]
    return "\n".join(lines)


parts = ["# Transition Tables",
         "_Generated by `scripts/build_assets.py` from the DFA objects used by the application._",
         "`→` marks the start state and `*` marks final states. `qd` is the trap state.\n"]
for title, dfa in [("ATM PIN DFA", PIN), ("Email DFA", EMAIL), ("Password product DFA", PWD)]:
    parts.append(f"## {title}\n")
    parts.append(f"|Q| = {len(dfa.states)}, Σ = {{{', '.join(dfa.symbols)}}}, "
                 f"q0 = `{dfa.start}`, F = {{{', '.join('`' + q + '`' for q in sorted(dfa.finals))}}}\n")
    parts.append(md_table(dfa.transition_table()) + "\n")
with open(os.path.join(ROOT, "docs", "transition_tables.md"), "w", encoding="utf-8") as f:
    f.write("\n".join(parts))
print("docs/transition_tables.md written")
